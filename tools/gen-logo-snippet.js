// node tools/gen-logo-snippet.js — research/logo/*.svg → theme/assets/sm-*.svg (optimised) + theme/snippets/sm-logo.liquid
// Source: SIGNATURE MEUBLE 2 VECT.pdf (converted by tools/pdf2svg.mjs + tools/logo-variants.js).
const fs = require('fs');
const round = s => s.replace(/-?\d+\.\d+/g, n => String(+(+n).toFixed(1)));
const files = { 'compact-dark': 'sm-logo-compact-dark', 'compact-light': 'sm-logo-compact-light', 'full-dark': 'sm-logo-dark', 'full-light': 'sm-logo-light', 'monogram-dark': 'sm-monogram-dark', 'monogram-light': 'sm-monogram-light' };
const dims = {};
for (const [name, src] of Object.entries(files)) {
  let s = fs.readFileSync(`research/logo/${src}.svg`, 'utf8').replace(/<\?xml[^>]*>/, '').replace(/\n/g, ' ');
  s = s.replace(/<defs>[\s\S]*?<\/defs>/, '').replace(/ clip-path="url\(#clip_1\)"/g, '').replace(/ xmlns:xlink="[^"]+"/, '').replace(/ version="1.1"/, '').replace(/ role="img" aria-label="Signature Meubles"/, '');
  s = round(s).replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  const vb = s.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number); dims[name] = [Math.round(vb[2] / 10), Math.round(vb[3] / 10)];
  s = s.replace('<svg ', `<svg width="${dims[name][0]}" height="${dims[name][1]}" `);
  fs.writeFileSync(`theme/assets/sm-logo-${name}.svg`, s); console.log(`sm-logo-${name}.svg`, (s.length / 1024).toFixed(1) + ' kB', dims[name]);
}
const snippet = `{%- comment -%}
  Signature Meubles vector logo. Assets generated by tools/gen-logo-snippet.js from the supplied vector PDF.
  Usage: {% render 'sm-logo', variant: 'compact' | 'full' | 'monogram', tone: 'dark' | 'light', class: '', loading: 'eager' %}
  dark = forêt + bronze (for ivory backgrounds) · light = white + light bronze (for forêt / photo backgrounds)
{%- endcomment -%}
{%- liquid
  assign v = variant | default: 'compact'
  assign t = tone | default: 'dark'
  case v
    when 'full'
      assign w = ${dims['full-dark'][0]}
      assign h = ${dims['full-dark'][1]}
    when 'monogram'
      assign w = ${dims['monogram-dark'][0]}
      assign h = ${dims['monogram-dark'][1]}
    else
      assign w = ${dims['compact-dark'][0]}
      assign h = ${dims['compact-dark'][1]}
  endcase
  assign file = 'sm-logo-' | append: v | append: '-' | append: t | append: '.svg'
-%}
<img src="{{ file | asset_url }}" width="{{ w }}" height="{{ h }}" alt="{{ alt | default: shop.name | escape }}" class="sm-logo sm-logo--{{ v }} {{ class }}" loading="{{ loading | default: 'lazy' }}" decoding="async">
`;
fs.writeFileSync('theme/snippets/sm-logo.liquid', snippet); console.log('snippet ok');
