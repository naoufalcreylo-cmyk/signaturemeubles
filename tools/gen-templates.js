// node tools/gen-templates.js — writes theme JSON templates + section groups from tools/site.js,
// and removes Hyper's alternate demo templates (they carry demo claims and are not assigned to anything).
const fs = require('fs'); const path = require('path');
const { groups, templates } = require('./site');
const T = 'theme';
const HEAD = '/*\n * Signature Meubles — generated by tools/gen-templates.js from tools/site.js.\n * Edits made in the theme editor are saved here by Shopify; re-generating overwrites them.\n */\n';

function normalise(sec) {
  const out = { type: sec.type };
  if (sec.disabled) out.disabled = true;
  if (sec.blocks) {
    out.blocks = {}; out.block_order = [];
    const seen = {};
    sec.blocks.forEach(b => { const id = b.id || `${b.type.replace(/[^a-z0-9]/gi, '_')}_${(seen[b.type] = (seen[b.type] || 0) + 1)}`;
      out.blocks[id] = { type: b.type, ...(b.disabled ? { disabled: true } : {}), settings: b.settings || {} }; out.block_order.push(id); });
  }
  out.settings = sec.settings || {};
  return out;
}
const write = (file, obj) => { fs.writeFileSync(path.join(T, file), HEAD + JSON.stringify(obj, null, 2) + '\n'); console.log('wrote', file); };

for (const [name, g] of Object.entries(groups)) write(`sections/${name}.json`, { name: g.name, type: g.type, sections: Object.fromEntries(Object.entries(g.sections).map(([k, s]) => [k, normalise(s)])), order: g.order });
for (const [name, t] of Object.entries(templates)) write(`templates/${name}.json`, { ...(t.layout ? { layout: t.layout } : {}), sections: Object.fromEntries(Object.entries(t.sections).map(([k, s]) => [k, normalise(s)])), order: t.order });

const DEMO = ['collection.banner-as-background', 'collection.banner-left', 'collection.banner-top-with-cards', 'collection.banner-without-image', 'product.coming-soon', 'product.flash-sale', 'product.grid-2-columns',
  'product.grid-mix', 'product.horizontal-thumbnails', 'product.out-of-stock', 'product.product-image-swatch', 'page.faq', 'page.find-a-store', 'page.customer-care'];
for (const d of DEMO) { const f = path.join(T, 'templates', d + '.json'); if (fs.existsSync(f)) { fs.unlinkSync(f); console.log('removed demo template', d); } }
